#!/bin/bash
# OpenVPN --up/--down hook: apply the DNS servers pushed by the VPN server (dhcp-option DNS/DNS6/DOMAIN) to
# /etc/resolv.conf through openresolv, exclusively (same as wg-quick's DNS=), and remove them again on down.

case "${script_type:-}" in
	up)
		nameservers=""
		search=""
		i=1
		while option_var="foreign_option_${i}" && [[ -n "${!option_var:-}" ]]; do
			option="${!option_var}"
			case "${option}" in
				"dhcp-option DNS "* | "dhcp-option DNS6 "*)
					nameservers="${nameservers}nameserver ${option##* }"$'\n'
					;;
				"dhcp-option DOMAIN "* | "dhcp-option DOMAIN-SEARCH "*)
					search="${search:+${search} }${option##* }"
					;;
			esac
			i=$((i + 1))
		done

		if [[ -z "${nameservers}" ]]; then
			echo "$(date +'%Y-%m-%d %H:%M:%S') [INFO] VPN server pushed no DNS servers, keeping the container's DNS settings"
			exit 0
		fi

		echo "$(date +'%Y-%m-%d %H:%M:%S') [INFO] Using the DNS servers pushed by the VPN server: $(awk 'NF { print $2 }' <<< "${nameservers}" | paste -sd, -)"
		{
			echo "# Generated by openvpn for interface ${dev}"
			if [[ -n "${search}" ]]; then
				echo "search ${search}"
			fi
			printf '%s' "${nameservers}"
		} | resolvconf -a "${dev}" -m 0 -x 2>/dev/null || echo "$(date +'%Y-%m-%d %H:%M:%S') [WARNING] resolvconf could not apply the pushed DNS servers"
		;;
	down)
		resolvconf -d "${dev}" 2>/dev/null || true
		;;
esac

exit 0
